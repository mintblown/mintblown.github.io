/* Integration checks in a real browser, no test framework or remote dependencies. */
(async function () {
  'use strict';
  const result=document.getElementById('result'),frame=document.getElementById('page');
  const key='mission-mausefallenauto-v1',before=localStorage.getItem(key);let count=0,errors=[];
  const assert=(ok,msg)=>{if(!ok)throw new Error(msg);count++;};
  const agree=async(w,persist=true)=>{
    const ready=new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Project startup timed out')),10000);w.document.addEventListener('trap:ready',()=>{clearTimeout(timer);resolve();},{once:true});});
    w.document.getElementById('project-consent-checkbox').checked=true;
    w.document.getElementById('project-consent-checkbox').dispatchEvent(new w.Event('change'));
    w.document.getElementById('project-save-later').checked=persist;
    w.document.getElementById('project-consent-start').click();await ready;
  };
  const load=(file,{consent=true,persist=true}={})=>new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(new Error('Loading '+file+' timed out')),15000);
    frame.onload=async()=>{
      const w=frame.contentWindow;w.confirm=()=>true;w.addEventListener('error',e=>errors.push(e.message));
      w.storageReads=0;w.storageWrites=0;
      const get=w.Storage.prototype.getItem,set=w.Storage.prototype.setItem;
      w.Storage.prototype.getItem=function(...args){w.storageReads++;return get.apply(this,args);};
      w.Storage.prototype.setItem=function(...args){w.storageWrites++;return set.apply(this,args);};
      try{if(consent&&!w.TrapBoot.blocked)await agree(w,persist);clearTimeout(timeout);resolve(w);}catch(error){clearTimeout(timeout);reject(error);}
    };
    frame.src='../'+file;
  });
  const input=(w,selector,value)=>{const e=w.document.querySelector(selector);assert(e,'Input exists: '+selector);e.value=value;e.dispatchEvent(new w.Event('input',{bubbles:true}));};
  const find=(w,selector)=>w.document.querySelector(selector);
  const text=(w,selector)=>find(w,selector)?.textContent||'';
  try {
    localStorage.removeItem(key);
    let w=await load('index.html',{consent:false});
    assert(!w.Trap&&find(w,'main').hidden&&find(w,'#project-consent').open,'Project gated before consent');
    assert(!find(w,'#project-consent-checkbox').checked&&!find(w,'#project-save-later').checked,'Both choices unchecked');
    find(w,'#project-consent-form').dispatchEvent(new w.Event('submit',{cancelable:true}));
    assert(!w.Trap&&w.storageReads===0&&w.storageWrites===0,'No initialization or storage without consent');
    find(w,'#project-save-later').click();assert(find(w,'#project-consent-start').disabled,'Persistence alone does not grant consent');
    await agree(w,true);
    assert(w.TrapBoot.ready&&!find(w,'#project-consent').open,'Consent starts project');
    assert(find(w,'#project-name')&&find(w,'#project-group')&&find(w,'#project-members'),'Basecamp has all identity fields');
    assert(find(w,'#basecamp-project #project-document')&&find(w,'#basecamp-project #save-project')&&find(w,'#basecamp-project #load-project'),'Project actions directly below identity fields');
    input(w,'#project-name','Ada');input(w,'#project-group','Team <b>Hebel</b>');input(w,'#project-members','Ada\nBen');
    assert(w.Trap.state.profile.name==='Ada'&&w.Trap.state.profile.members==='Ada\nBen','Identity fields update project data');
    const report=w.TrapDocument.render(w.Trap.state),doc=new w.DOMParser().parseFromString(report,'text/html');
    const sections=[...doc.querySelectorAll('main>section h2')].map(node=>node.textContent);
    assert(sections[0]==='1 · Name und Gruppe'&&sections[1]==='2 · Unser Bearbeitungsstand','Report starts with group and progress');
    assert(doc.querySelector('.project-identity').textContent.includes('Team <b>Hebel</b>')&&!doc.querySelector('.project-identity b'),'Profile safely displayed as text');
    const imported={...w.Trap.state,profile:{name:'Ben',groupName:'Geladene Gruppe',members:'Ben\nAda'}};
    const transfer=new w.DataTransfer();transfer.items.add(new w.File([w.TrapBackup.encode(imported)],'projekt.json',{type:'application/json'}));
    const importFinished=new Promise((resolve,reject)=>{
      const timer=setTimeout(()=>reject(new Error('Project import timed out')),15000),previous=frame.onload;
      frame.onload=async event=>{await previous(event);const next=frame.contentWindow;if(!next.TrapBoot.ready)await agree(next,true);clearTimeout(timer);resolve(next);};
    });
    find(w,'#project-file').files=transfer.files;find(w,'#project-file').dispatchEvent(new w.Event('change'));
    w=await importFinished;
    assert(find(w,'#project-name').value==='Ben'&&find(w,'#project-group').value==='Geladene Gruppe'&&find(w,'#project-members').value==='Ben\nAda','Loading project restores identity fields');
    assert(w.document.querySelectorAll('[data-destination]').length===8,'All 8 destinations');
    assert(w.document.querySelectorAll('.station-card[href]').length===3,'Only three active direct links');
    assert(w.document.querySelectorAll('[data-destination][aria-disabled="true"]').length===5,'Five map stations disabled');
    assert(w.document.querySelectorAll('.disabled-map-overlay clipPath rect').length===5,'Grayscale overlays cover five inactive regions');
    assert([...w.document.images].every(i=>i.complete&&i.naturalWidth>0),'Map image loaded');
    w.matchMedia=()=>({matches:true});
    w.requestAnimationFrame=callback=>w.setTimeout(()=>callback(w.performance.now()),0);
    assert(find(w,'#start-lesson').hidden,'Start button hidden at basecamp');
    await w.TrapTravel.travel('goldene-regel');
    assert(!find(w,'#start-lesson').hidden,'Start button appears on arrival');
    assert(find(w,'#traveller #start-lesson'),'Start button is above traveller');
    assert(w.TrapTravel.current==='goldene-regel','Arrival tracked');
    await w.TrapTravel.travel('reibung');
    assert(w.TrapTravel.current==='goldene-regel','Disabled travel rejected');
    await w.TrapTravel.travel('hebel');assert(w.TrapTravel.current==='hebel','Other active stations remain reachable');
    await w.TrapTravel.travel('goldene-regel');
    assert(w.document.querySelectorAll('.island-road').length===16,'All visible roads have motion paths');
    assert(find(w,'#open-station').getAttribute('href').includes('goldene-regel.html'),'Ramp freely reachable');
    w=await load('federkraft.html');
    assert(w.Trap.state.profile.groupName==='Geladene Gruppe','Identity persists across lesson navigation');
    assert(w.TrapTables,'Tables script initialized');
    assert(w.TrapGlossary,'Glossary initializes');
    const term=find(w,'.term');assert(term&&term.tabIndex===0,'Technical terms focusable');
    term.focus();assert(!find(w,'#physics-tooltip').hidden,'Definition shown on focus');
    assert(text(w,'#physics-tooltip').length>20,'Definition has explanatory text');
    w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
    assert(find(w,'#physics-tooltip').hidden,'Escape closes explanation');
    assert(w.Trap.state.tables.spring.every(r=>!r.angle&&!r.force),'No invented measurements');
    assert(w.Trap.state.tables.spring.length===6,'Six empty measurement rows prepared');
    assert(text(w,'[data-message]').includes('0 von mindestens 6'),'Minimum distinct-angle target visible');
    input(w,'[data-row="0"] [data-field="angle"]','90');
    input(w,'[data-row="0"] [data-field="force"]','2,5');
    assert(w.document.querySelectorAll('#spring-chart circle').length===1,'Point appears after decimal-comma input');
    input(w,'[data-row="1"] [data-field="angle"]','30');
    input(w,'[data-row="1"] [data-field="force"]','1,2');
    assert(w.document.querySelectorAll('#spring-chart circle').length===2,'Second real point');
    const points=find(w,'#spring-chart polyline').getAttribute('points').split(' ');
    assert(Number(points[0].split(',')[0])<Number(points[1].split(',')[0]),'Chart sorted by angle');
    input(w,'[data-row="0"] [data-field="force"]','-1');
    assert(find(w,'[data-row="0"] [data-field="force"]').getAttribute('aria-invalid')==='true','Negative force rejected');
    assert(w.document.querySelectorAll('#spring-chart circle').length===1,'Invalid measurement excluded');
    input(w,'[data-row="0"] [data-field="force"]','2,5');
    input(w,'#arm-angle','0');assert(text(w,'#spring-view').includes('90°'),'Correct geometry guidance');
    input(w,'#arm-angle','180');assert(!find(w,'#spring-view').innerHTML.includes('NaN'),'Extreme geometry valid');
    [60,110,140,160].forEach((angle,index)=>{
      input(w,`[data-row="${index+2}"] [data-field="angle"]`,String(angle));
      input(w,`[data-row="${index+2}"] [data-field="force"]`,'2');
    });
    assert(text(w,'[data-message]').includes('6 von mindestens 6'),'Six distinct complete measurements recognized');
    input(w,'[data-row="5"] [data-field="angle"]','140');
    assert(text(w,'[data-message]').includes('5 von mindestens 6'),'Repeated angle does not count twice');
    input(w,'[data-row="5"] [data-field="angle"]','160');
    find(w,'#explored').click();
    assert(!find(w,'#results-reminder').hidden&&text(w,'#results-reminder').includes('Goodnotes'),'Checking station completion shows documentation reminder');
    assert(find(w,'#results-message').open&&text(w,'#results-message').includes('Goodnotes'),'Checking completion opens Goodnotes message');
    find(w,'#results-message button').click();assert(!find(w,'#results-message').open,'Message can be acknowledged');
    find(w,'#explored').click();
    assert(find(w,'#results-reminder').hidden,'Unchecking completion hides reminder');
    assert(!find(w,'#results-message').open,'Unchecking does not open message');
    find(w,'#explored').click();
    assert(find(w,'#results-message').open,'Checking again shows message again');find(w,'#results-message button').click();
    w=await load('federkraft.html');
    assert(find(w,'[data-row="0"] [data-field="force"]').value==='2,5','Persistence across page loads');
    assert(find(w,'#explored').checked,'Self-marked progress persisted');
    assert(!find(w,'#results-reminder').hidden,'Documentation reminder visible for completed station on return');
    assert(!find(w,'#results-message').open,'Restoring completed state does not interrupt with message');
    find(w,'[data-delete="0"]').click();
    assert(w.document.querySelectorAll('tbody tr').length===5,'Delete row');
    find(w,'[data-add]').click();assert(w.document.querySelectorAll('tbody tr').length===6,'Add row');
    w=await load('hebel.html');
    assert(w.Trap.state.tables.lever.length===6,'Six partner rounds prepared');
    assert(find(w,'#plate-total-force').value==='','No invented plate force');
    assert(text(w,'[data-row="0"]').includes('A gibt vor')&&text(w,'[data-row="1"]').includes('B gibt vor'),'Partner roles alternate');
    input(w,'#plate-count','0');input(w,'#plate-total-force','0,5');
    assert(find(w,'#plate-count').getAttribute('aria-invalid')==='true','Zero plate count rejected');
    input(w,'#plate-count','5');
    assert(text(w,'#plate-force-result').includes('0,1 N'),'Measured total force divided by plate count');
    assert(w.TrapBackup.decode(w.TrapBackup.encode(w.Trap.state)).controls.hebel['plate-total-force']==='0,5','Plate measurement included in portable backup');
    w=await load('hebel.html');
    assert(find(w,'#plate-count').value==='5'&&text(w,'#plate-force-result').includes('0,1 N'),'Plate measurement restored');
    for(const [field,value]of Object.entries({f1:'2',l1:'20',f2:'4',l2:'10'}))input(w,`[data-row="0"] [data-field="${field}"]`,value);
    assert(text(w,'[data-message]').includes('1 von mindestens 6'),'Partner-round progress shown');
    assert(text(w,'[data-row="0"] [data-output="0"]')==='40','Left product calculated');
    assert(text(w,'[data-row="0"] [data-output="2"]')==='0','Balanced lever difference');
    input(w,'#lever-length','40');input(w,'#lever-angle','140');
    assert(text(w,'#lever-result').includes('0,38'),'Lever inverse force relationship');
    w=await load('goldene-regel.html');
    assert(w.Trap.state.tables.ramp.length===5,'Five height measurements prepared');
    assert(find(w,'#draw-ramp-forces').disabled,'No force drawing without measured lifting force');
    for(const [field,value]of Object.entries({s:'1',h:'0,1',force:'1,4',weight:'10'}))input(w,`[data-row="0"] [data-field="${field}"]`,value);
    assert(text(w,'[data-row="0"] [data-output="0"]')==='1,4','Pull work calculated');
    assert(text(w,'[data-row="0"] [data-output="1"]')==='1','Lift work calculated');
    assert(text(w,'[data-message]').includes('1 von mindestens 5'),'Height progress without optional measurement');
    [0.04,0.06,0.08,0.12].forEach((h,index)=>{
      for(const [field,value]of Object.entries({s:'1',h:String(h),force:String(h*10+.4),weight:'10'}))input(w,`[data-row="${index+1}"] [data-field="${field}"]`,value);
    });
    assert(text(w,'[data-message]').includes('5 von mindestens 5'),'Five distinct heights counted');
    assert(!text(w,'[data-message]').includes('Hubhöhe gleich'),'Different heights no longer warned against');
    input(w,'[data-row="4"] [data-field="h"]','0,1');assert(text(w,'[data-message]').includes('4 von mindestens 5'),'Repeated height not counted twice');
    input(w,'[data-row="4"] [data-field="h"]','0,12');
    input(w,'[data-row="0"] [data-field="lift"]','9,95');
    assert(!find(w,'#draw-ramp-forces').disabled,'Optional measurement enables force construction');
    find(w,'#draw-ramp-forces').click();
    assert(w.document.querySelectorAll('#ramp-force-drawing svg').length===2,'Force directions and geometric addition shown');
    const arrows=[...w.document.querySelectorAll('#ramp-force-drawing figure:nth-child(2) .force-arrow line')];
    const same=(a,k,b,l)=>Math.abs(Number(a.getAttribute(k))-Number(b.getAttribute(l)))<1e-7;
    assert(same(arrows[1],'x2',arrows[2],'x1')&&same(arrows[1],'y2',arrows[2],'y1'),'Force arrows joined tip to tail');
    assert(same(arrows[3],'x1',arrows[1],'x1')&&same(arrows[3],'x2',arrows[2],'x2')&&same(arrows[3],'y2',arrows[2],'y2'),'Resultant spans first start to final tip');
    const length=line=>Math.hypot(Number(line.getAttribute('x2'))-Number(line.getAttribute('x1')),Number(line.getAttribute('y2'))-Number(line.getAttribute('y1')));
    assert(Math.abs(length(arrows[1])/length(arrows[2])-1.4/9.95)<1e-7,'One geometric scale for both measured forces');
    assert(text(w,'#ramp-force-drawing').includes('Orange'),'Measured discrepancy remains visible');
    const forceModel=w.TrapModel.rampForces(1,.6,6,8,10);
    assert(Math.abs(forceModel.sum.y-10)<1e-9&&Math.abs(forceModel.gap)<1e-9,'Ideal force sum balances weight');
    find(w,'#ramp-force-mode').value='ideal';find(w,'#ramp-force-mode').dispatchEvent(new w.Event('change'));
    assert(text(w,'#ramp-force-drawing').includes('Ideales Vergleichsmodell')&&!text(w,'#ramp-force-drawing').includes('Orange'),'Ideal view distinguished from measured values');
    assert(w.TrapBackup.decode(w.TrapBackup.encode(w.Trap.state)).tables.ramp[0].lift==='9,95','Optional force preserved in backup');
    const legacy=w.TrapBackup.decode(JSON.stringify({format:'mission-mausefallenauto',version:1,data:{tables:{ramp:[{s:'1',h:'0.1',force:'1',weight:'10'}]},controls:{},explored:{}}}));
    assert(legacy.tables.ramp[0].lift==='','Older project files load with unmeasured optional force');
    input(w,'[data-row="0"] [data-field="lift"]','-1');
    assert(find(w,'#draw-ramp-forces').disabled&&text(w,'[data-row="0"] [data-output="0"]')==='1,4','Invalid extra measurement blocks drawing, not base work calculation');
    input(w,'[data-row="0"] [data-field="lift"]','9,95');
    input(w,'[data-row="0"] [data-field="h"]','2');
    assert(text(w,'[data-message]').includes('größer'),'Impossible ramp feedback');
    for(const page of ['uebersetzung','raeder','reibung','rechnen','testgelaende']){
      w=await load(page+'.html');
      assert(w.TrapBoot.blocked&&!w.Trap,'Disabled direct page has no running project: '+page);
      assert(text(w,'main').includes('vorerst deaktiviert'),'Disabled page explains availability');
      assert(w.storageReads===0&&w.storageWrites===0,'Disabled page has no storage access');
    }
    const stored=localStorage.getItem(key);
    w=await load('hebel.html',{persist:false});
    assert(w.storageReads===0&&w.storageWrites===0,'Session-only startup does not read or write storage');
    assert(find(w,'#plate-count').value==='','Session-only mode does not load old data');
    input(w,'#plate-count','2');input(w,'#plate-total-force','0,4');
    assert(text(w,'#plate-force-result').includes('0,2 N'),'Session-only experiment works');
    assert(w.storageReads===0&&w.storageWrites===0&&localStorage.getItem(key)===stored,'Session-only edits preserve old saved data');
    w=await load('index.html');assert(find(w,'[data-destination="federkraft"]').classList.contains('visited'),'Map self-progress');
    assert(text(w,'#map-progress').includes('1 / 3'),'Progress counts only active stations');
    const reloaded=new Promise(resolve=>{frame.onload=resolve;});
    find(w,'#withdraw-project-consent').click();await reloaded;w=frame.contentWindow;
    assert(!w.Trap&&find(w,'#project-consent').open,'Withdrawal returns to consent gate');
    assert(localStorage.getItem(key)===null,'Withdrawal deletes persistent project data');
    assert(errors.length===0,'No runtime errors: '+errors.join(', '));
    result.textContent='PASS: '+count+' browser checks. Three active stations, disabled routes, consent, session-only mode, real tables, force diagrams, storage and withdrawal.';
  } catch(error){result.textContent='FAIL: '+error.stack;}
  finally{if(before===null)localStorage.removeItem(key);else localStorage.setItem(key,before);}
})();
