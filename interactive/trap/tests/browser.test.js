/* Integration checks in a real browser, no test framework or remote dependencies. */
(async function () {
  'use strict';
  const result=document.getElementById('result'),frame=document.getElementById('page');
  const key='mission-mausefallenauto-v1',before=localStorage.getItem(key);let count=0,errors=[];
  const assert=(ok,msg)=>{if(!ok)throw new Error(msg);count++;};
  const load=file=>new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(new Error('Loading '+file+' timed out')),10000);
    frame.onload=()=>{clearTimeout(timeout);const w=frame.contentWindow;w.confirm=()=>true;w.addEventListener('error',e=>errors.push(e.message));resolve(w);};
    frame.src='../'+file;
  });
  const input=(w,selector,value)=>{const e=w.document.querySelector(selector);assert(e,'Input exists: '+selector);e.value=value;e.dispatchEvent(new w.Event('input',{bubbles:true}));};
  const find=(w,selector)=>w.document.querySelector(selector);
  const text=(w,selector)=>find(w,selector)?.textContent||'';
  try {
    localStorage.removeItem(key);
    let w=await load('index.html');
    assert(w.document.querySelectorAll('[data-destination]').length===8,'All 8 destinations');
    assert(w.document.querySelectorAll('.station-card').length===8,'Direct links to all stations');
    assert([...w.document.images].every(i=>i.complete&&i.naturalWidth>0),'Map image loaded');
    w.matchMedia=()=>({matches:true});
    w.requestAnimationFrame=callback=>w.setTimeout(()=>callback(w.performance.now()),0);
    assert(find(w,'#start-lesson').hidden,'Start button hidden at basecamp');
    await w.TrapTravel.travel('goldene-regel');
    assert(!find(w,'#start-lesson').hidden,'Start button appears on arrival');
    assert(find(w,'#traveller #start-lesson'),'Start button is above traveller');
    assert(w.TrapTravel.current==='goldene-regel','Arrival tracked');
    await w.TrapTravel.travel('reibung');
    assert(w.TrapTravel.current==='reibung','Cross-island travel follows connected roads');
    await w.TrapTravel.travel('goldene-regel');
    assert(w.document.querySelectorAll('.island-road').length===16,'All visible roads have motion paths');
    assert(find(w,'#open-station').getAttribute('href').includes('goldene-regel.html'),'Ramp freely reachable');
    w=await load('federkraft.html');
    assert(w.TrapTables,'Tables script initialized');
    assert(w.TrapGlossary,'Glossary initializes');
    const term=find(w,'.term');assert(term&&term.tabIndex===0,'Technical terms focusable');
    term.focus();assert(!find(w,'#physics-tooltip').hidden,'Definition shown on focus');
    assert(text(w,'#physics-tooltip').length>20,'Definition has explanatory text');
    w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
    assert(find(w,'#physics-tooltip').hidden,'Escape closes explanation');
    assert(w.Trap.state.tables.spring.every(r=>!r.angle&&!r.force),'No invented measurements');
    input(w,'[data-row="0"] [data-field="angle"]','90');
    input(w,'[data-row="0"] [data-field="force"]','2,5');
    assert(w.document.querySelectorAll('#spring-chart circle').length===1,'Point appears after decimal-comma input');
    input(w,'[data-row="1"] [data-field="angle"]','30');
    input(w,'[data-row="1"] [data-field="force"]','1,2');
    assert(w.document.querySelectorAll('#spring-chart circle').length===2,'Second real point');
    const points=find(w,'#spring-chart polyline').getAttribute('points').split(' ');
    assert(Number(points[0].split(',')[0])<Number(points[1].split(',')[0]),'Chart sorted by angle');
    input(w,'[data-row="0"] [data-field="force"]','-1');
    assert(find(w,'[data-row="0"] [data-field="force"]').getAttribute('aria-invalid')==='true','Negative force rejected');
    assert(w.document.querySelectorAll('#spring-chart circle').length===1,'Invalid measurement excluded');
    input(w,'[data-row="0"] [data-field="force"]','2,5');
    input(w,'#arm-angle','0');assert(text(w,'#spring-view').includes('90°'),'Correct geometry guidance');
    input(w,'#arm-angle','180');assert(!find(w,'#spring-view').innerHTML.includes('NaN'),'Extreme geometry valid');
    find(w,'#explored').click();
    w=await load('federkraft.html');
    assert(find(w,'[data-row="0"] [data-field="force"]').value==='2,5','Persistence across page loads');
    assert(find(w,'#explored').checked,'Self-marked progress persisted');
    find(w,'[data-delete="0"]').click();
    assert(w.document.querySelectorAll('tbody tr').length===2,'Delete row');
    find(w,'[data-add]').click();assert(w.document.querySelectorAll('tbody tr').length===3,'Add row');
    w=await load('hebel.html');
    for(const [field,value]of Object.entries({f1:'2',l1:'20',f2:'4',l2:'10'}))input(w,`[data-row="0"] [data-field="${field}"]`,value);
    assert(text(w,'[data-row="0"] [data-output="0"]')==='40','Left product calculated');
    assert(text(w,'[data-row="0"] [data-output="2"]')==='0','Balanced lever difference');
    input(w,'#lever-length','40');input(w,'#lever-angle','140');
    assert(text(w,'#lever-result').includes('0,38'),'Lever inverse force relationship');
    w=await load('goldene-regel.html');
    for(const [field,value]of Object.entries({s:'1',h:'0,1',force:'1,4',weight:'10'}))input(w,`[data-row="0"] [data-field="${field}"]`,value);
    assert(text(w,'[data-row="0"] [data-output="0"]')==='1,4','Pull work calculated');
    assert(text(w,'[data-row="0"] [data-output="1"]')==='1','Lift work calculated');
    input(w,'[data-row="0"] [data-field="h"]','2');
    assert(text(w,'[data-message]').includes('größer'),'Impossible ramp feedback');
    w=await load('uebersetzung.html');
    const thin=text(w,'#transmission-result');
    input(w,'#winding-mode','drum');
    assert(find(w,'#winding-radius').value==='15','Switch to winding disc');
    assert(text(w,'#transmission-result')!==thin,'Winding mode updates model');
    input(w,'#winding-radius','30');assert(!find(w,'#transmission-view').innerHTML.includes('NaN'),'Transmission geometry finite');
    w=await load('raeder.html');
    input(w,'#wheel-turns','0.25');input(w,'#wheel-radius','15');input(w,'#roll-progress','100');
    assert(text(w,'#wheel-result').includes('0,24 m'),'Quarter turn rolling distance');
    assert(!find(w,'#wheel-view').innerHTML.includes('NaN'),'Wheel geometry finite');
    w=await load('reibung.html');input(w,'#grip','0');
    assert(text(w,'#friction-result').includes('durchdrehen'),'Low grip explanation');
    input(w,'#grip','100');input(w,'#bearing','100');input(w,'#rolling','100');
    assert(text(w,'#friction-result').includes('Hohe Lager'),'High losses explanation');
    w=await load('rechnen.html');
    assert(find(w,'#calc-length').value==='','No invented car dimensions');
    for(const [id,value]of Object.entries({'calc-length':'100','calc-axle':'3','calc-wheel':'6'}))input(w,'#'+id,value);
    assert(text(w,'#calculation-result').includes('20 m'),'Unit conversion: 20 meters');
    input(w,'#calc-axle','0');assert(find(w,'#calc-axle').getAttribute('aria-invalid')==='true','Zero radius rejected');
    input(w,'#calc-axle','3');
    w=await load('testgelaende.html');find(w,'#import-dimensions').click();
    assert(w.Trap.state.tables.trials[1].length==='100','Calculator dimensions imported');
    input(w,'[data-row="1"] [data-field="unwind"]','18');
    input(w,'[data-row="1"] [data-field="total"]','23');
    assert(text(w,'[data-row="1"] [data-output="1"]')==='5','Coasting distance');
    assert(text(w,'[data-row="1"] [data-output="2"]')==='3','Larger total distance accepted');
    input(w,'[data-row="1"] [data-field="total"]','17');
    assert(text(w,'[data-message]').includes('nicht kleiner'),'Inconsistent total rejected');
    input(w,'[data-row="1"] [data-field="total"]','23');
    input(w,'[data-row="1"] [data-field="change"]','<img src=x onerror=alert(1)>');
    w=await load('testgelaende.html');assert(!w.document.querySelector('td img'),'Free text escaped on reload');
    assert(w.document.querySelectorAll('#trials-chart .screenshot').length===1,'Screenshot reminder at chart');
    find(w,'#export-csv').click();assert(text(w,'#trial-status').includes('CSV'),'CSV handler runs');
    w=await load('index.html');assert(find(w,'[data-destination="federkraft"]').classList.contains('visited'),'Map self-progress');
    assert(text(w,'#map-progress').includes('1 / 8'),'Progress includes all 8 stations');
    assert(errors.length===0,'No runtime errors: '+errors.join(', '));
    result.textContent='PASS: '+count+' browser checks. All eight stations, real tables, validation, diagrams, storage, navigation and CSV.';
  } catch(error){result.textContent='FAIL: '+error.stack;}
  finally{if(before===null)localStorage.removeItem(key);else localStorage.setItem(key,before);}
})();
